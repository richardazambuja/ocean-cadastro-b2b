import {readFileSync,writeFileSync,copyFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
const root=resolve('../..');
const manifest=JSON.parse(readFileSync('reports/local-source-hashes.json'));
const panel=resolve(root,'extensions/app-home/src/AppHome.jsx');
const hash=createHash('sha256').update(readFileSync(panel)).digest('hex');
if(hash!==manifest.hashes['AppHome.jsx']) throw Error('Painel local mudou; nao sobrescrever.');
const verify=spawnSync('git',['apply','--check',resolve('integration/panel.patch')],{cwd:root,encoding:'utf8'});
if(verify.error||verify.status!==0)throw Error(verify.error?.message||verify.stderr);
const result=spawnSync('git',['apply',resolve('integration/panel.patch')],{cwd:root,encoding:'utf8'});
if(result.error||result.status!==0)throw Error(result.error?.message||result.stderr);
const dest=resolve(root,'extensions/app-home/src/flow-bridge');mkdirSync(dest,{recursive:true});
for(const name of ['state.mjs','operations.mjs','bridge.mjs'])copyFileSync('src/'+name,resolve(dest,name));
copyFileSync('integration/flow-bridge-production.mjs',resolve(root,'extensions/app-home/src/flow-bridge-app.mjs'));
let text=readFileSync(panel,'utf8');
const before='      setDecisions(decisoes);';
if(!text.includes(before))throw Error('Nao localizado carregamento do painel.');
text=text.replace(before,before+'\n      const syncWarnings=await ponteFlow.syncLoaded(locais);\n      if(syncWarnings.length) setError("Sincronizacao de avisos requer revisao: "+syncWarnings.join("; "));');
writeFileSync(panel,text);
const toml=resolve(root,'shopify.app.toml');
let config=readFileSync(toml,'utf8');
config=config.replace('scopes = "write_products,read_companies,write_companies,read_customers"','scopes = "write_products,read_companies,write_companies,read_customers,read_metaobjects,write_metaobjects"');
writeFileSync(toml,config);
const ext=resolve(root,'extensions/app-home/shopify.extension.toml');
writeFileSync(ext,readFileSync(ext,'utf8').replace('scopes = "read_companies,read_customers,write_companies"','scopes = "read_companies,read_customers,write_companies,read_metaobjects,write_metaobjects"'));
console.log('Production bridge applied to current local app; runtime rollout remains disabled until configured.');
